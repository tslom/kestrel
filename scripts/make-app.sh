#!/bin/bash
# Build a double-clickable "Kestrel.app" for this machine.
#
# The bundle is machine-specific (absolute paths baked in) and gitignored —
# regenerate it any time with:  ./scripts/make-app.sh
# It launches the pywebview desktop launcher (backend/launch_app.py) with no
# Terminal window, and shows up as its own Dock icon while running.
#
# You do NOT need to re-run this after changing frontend code: the launcher
# rebuilds frontend/dist itself when sources are newer. Re-run it when the
# repo moves, when node/claude move to a different prefix, or after a
# `brew upgrade python@3.12` (see the interpreter copy below).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$REPO/Kestrel.app"
# The bundle's name before the rename. Left behind, it keeps a second
# registration in LaunchServices and a stale icon in Spotlight.
OLD_APP="$REPO/Vault Dashboard.app"
MACOS="$APP/Contents/MacOS"
RES="$APP/Contents/Resources"
VENV="$REPO/backend/.venv"
LOG=/tmp/vault-dashboard-app.log

# A Finder launch inherits none of your shell PATH — it gets
# /usr/gnu/bin:/usr/local/bin:/bin:/usr/bin and nothing else. Both tools the
# app shells out to live outside that: npm (the launcher's frontend rebuild)
# and claude (every console session). Resolve them now and bake in their dirs,
# which is the same posture as the absolute repo path below.
need_dirs=()
for tool in npm node claude; do
  if p="$(command -v "$tool" 2>/dev/null)"; then
    need_dirs+=("$(dirname "$p")")
  else
    echo "WARNING: '$tool' not found on PATH — the app will be missing it." >&2
  fi
done
# de-dupe, preserving order
EXTRA_PATH="$(printf '%s\n' "${need_dirs[@]}" | awk '!seen[$0]++' | paste -sd: -)"
echo "Baking PATH prefix: $EXTRA_PATH"

# Which interpreter binary the app runs as decides who macOS thinks it is.
# CoreFoundation resolves the venv's python symlink to the real framework
# binary and walks *up* from there, landing in Python.framework's own
# Python.app — so the menu bar said "Python", the Dock showed the generic
# rocket, and the bundle id was org.python.python no matter what our
# Info.plist claimed. Copying the framework's tiny launcher stub into this
# bundle puts the running executable *inside* us, and the identity is ours.
STUB_SRC="$("$VENV/bin/python" -c 'import sys, os; print(os.path.join(sys.base_prefix, "Resources/Python.app/Contents/MacOS/Python"))')"

echo "Building frontend (npm run build)…"
npm --prefix "$REPO/frontend" run build

echo "Assembling $APP …"
if [ -d "$OLD_APP" ]; then
  /System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister \
    -u "$OLD_APP" 2>/dev/null || true
  rm -rf "$OLD_APP"
  echo "Removed the old $OLD_APP"
fi
rm -rf "$APP"
mkdir -p "$MACOS" "$RES"
cp "$REPO/scripts/dashboard.icns" "$RES/icon.icns"

if [ -x "$STUB_SRC" ]; then
  cp "$STUB_SRC" "$MACOS/Kestrel"
  chmod +x "$MACOS/Kestrel"
  echo "Bundled interpreter: $STUB_SRC"
else
  # Non-framework build (pyenv without --enable-framework, say). The app still
  # works; it just shows up as Python. The run script falls back on its own.
  echo "WARNING: no framework stub at $STUB_SRC — the app will be named" >&2
  echo "         'Python' in the menu bar and Dock." >&2
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Kestrel</string>
  <key>CFBundleDisplayName</key><string>Kestrel</string>
  <!-- Kept from before the rename to Kestrel: the id is what the microphone
       grant and Launch Services know this app by. -->
  <key>CFBundleIdentifier</key><string>local.vault-dashboard</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>run</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <!-- Voice console. Without this key macOS refuses the microphone outright
       (and for a direct AVFoundation request would kill the process); the
       string is what the system permission dialog shows, once, per app. -->
  <key>NSMicrophoneUsageDescription</key><string>Talk to the console instead of typing. Audio is transcribed on this Mac and never leaves it.</string>
</dict>
</plist>
PLIST

cat > "$MACOS/run" <<RUN
#!/bin/bash
# Generated by scripts/make-app.sh — do not edit; regenerate instead.
# Redirect everything from here down, so the fallback notice below is logged
# too. -u on the interpreter: block-buffered stdout through this redirect
# means a crash flushes nothing and the log reads empty exactly when you need
# it.
exec >> "$LOG" 2>&1
echo "=== launch \$(date '+%Y-%m-%d %H:%M:%S') ==="

export PATH="$EXTRA_PATH:\$PATH"
# The CLI subscription login is shadowed by an API key, and a Finder launch
# can still pick one up from a shell profile a wrapper sourced. Belt and
# braces: the console must use the subscription.
unset ANTHROPIC_API_KEY
cd "$REPO/backend"

HERE="\$(cd "\$(dirname "\$0")" && pwd)"
STUB="\$HERE/Kestrel"

# Run the bundled interpreter with the venv's packages rather than the venv's
# python: sys.executable has to stay inside this bundle for the app to keep
# its own name and icon. Globbed, so a python minor bump doesn't need an edit.
SITE=(\$(echo "$VENV"/lib/python*/site-packages))

# The stub is linked against an exact Cellar path, so \`brew upgrade python\`
# leaves a copy that can't load. Probe it — launching as "Python" beats not
# launching, and the log says how to fix it.
if [ -x "\$STUB" ] && [ -d "\${SITE[0]:-}" ] && "\$STUB" -c "" 2>/dev/null; then
  export PYTHONPATH="\${SITE[0]}"
  exec "\$STUB" -u launch_app.py
fi

echo "[app] bundled interpreter unusable — falling back to the venv."
echo "[app] the window will be named 'Python'; re-run scripts/make-app.sh to fix."
source .venv/bin/activate
exec python -u launch_app.py
RUN
chmod +x "$MACOS/run"

# Signed, ad-hoc. Notification Center refuses an unsigned bundle outright
# (UNErrorDomain 1, "Notifications are not allowed for this application"), and
# the stub still carries Python's own signature, identifier org.python.python;
# re-signing it as ours makes process and bundle agree. Ad-hoc needs no
# Apple account — it's what Xcode's "Sign to Run Locally" does. The cdhash
# changes with every build either way, so the Full Disk Access re-add after a
# rebuild is unchanged.
if [ -x "$MACOS/Kestrel" ]; then
  codesign --force --sign - --identifier local.vault-dashboard "$MACOS/Kestrel"
fi
codesign --force --sign - "$APP"

# LaunchServices caches the old identity (it saw this path as org.python.python
# on every previous launch). Without this the Dock keeps the rocket icon until
# a logout.
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister \
  -f "$APP" 2>/dev/null || true

echo "Done. Launch it from Finder ($APP) or drag it to your Dock."
